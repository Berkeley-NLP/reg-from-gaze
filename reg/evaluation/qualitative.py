"""
Qualitative visualization of speaker referring expressions and listener gaze scanpaths.
"""

from typing import List, Optional, Sequence, Tuple, Union
import numpy as np
from PIL import Image, ImageDraw, ImageFont

from data.processing import is_point_in_bbox, COORDINATE_SCALE


def draw_gaze_trajectory(
    image: Image.Image,
    target_bbox_100: Tuple[float, float, float, float],
    gaze_points_100: Sequence[Optional[Sequence[float]]],
    caption: str = "",
    is_success: Optional[bool] = None,
    point_radius: int = 4,
    line_width: int = 2,
) -> Image.Image:
    """
    Render a qualitative visualization of the referring expression game:
      - Draws target bounding box (green if success, red if failure).
      - Draws gaze sequence scanpath with connected arrows/lines.
      - Annotates with caption banner.

    Args:
        image: Base PIL Image (letterboxed listener image, e.g. 512x320).
        target_bbox_100: (x1, y1, x2, y2) in 0-100 normalized space.
        gaze_points_100: Sequence of (x, y) or (x, y, sigma) coordinates in 0-100 space.
        caption: Text description generated by speaker.
        is_success: Optional flag indicating whether expression was grounded.
        point_radius: Circle radius in pixels for scanpath fixations.
        line_width: Width of trajectory lines.

    Returns:
        Annotated PIL Image.
    """
    vis_img = image.copy().convert("RGB")
    draw = ImageDraw.Draw(vis_img)
    w, h = vis_img.size

    # Convert target bbox from 0-100 to pixel coordinates
    bx1, by1, bx2, by2 = target_bbox_100
    px_x1 = int(bx1 / COORDINATE_SCALE * w)
    px_y1 = int(by1 / COORDINATE_SCALE * h)
    px_x2 = int(bx2 / COORDINATE_SCALE * w)
    px_y2 = int(by2 / COORDINATE_SCALE * h)

    # Determine success if not explicitly given
    if is_success is None:
        last_pt = None
        for pt in reversed(gaze_points_100):
            if pt is not None:
                last_pt = pt[:2]
                break
        is_success = bool(last_pt and is_point_in_bbox((last_pt[0], last_pt[1]), target_bbox_100))

    bbox_color = (0, 230, 0) if is_success else (255, 60, 60)
    draw.rectangle([px_x1, px_y1, px_x2, px_y2], outline=bbox_color, width=3)

    # Convert valid gaze points to pixel coordinates
    pixel_points: List[Tuple[int, int]] = []
    for pt in gaze_points_100:
        if pt is not None:
            gx = int(pt[0] / COORDINATE_SCALE * w)
            gy = int(pt[1] / COORDINATE_SCALE * h)
            pixel_points.append((gx, gy))

    # Draw scanpath lines
    if len(pixel_points) > 1:
        for i in range(len(pixel_points) - 1):
            p_start = pixel_points[i]
            p_end = pixel_points[i + 1]
            draw.line([p_start, p_end], fill=(255, 215, 0), width=line_width)

    # Draw fixation points
    for idx, (gx, gy) in enumerate(pixel_points):
        # Color transition from initial (cyan) to final (magenta)
        r = point_radius + (2 if idx == len(pixel_points) - 1 else 0)
        pt_color = (0, 255, 255) if idx == 0 else ((255, 0, 255) if idx == len(pixel_points) - 1 else (255, 255, 0))
        draw.ellipse([gx - r, gy - r, gx + r, gy + r], fill=pt_color, outline=(0, 0, 0))

    # Add text banner at top or bottom
    if caption:
        banner_h = 32
        banner = Image.new("RGB", (w, h + banner_h), color=(20, 20, 20))
        banner.paste(vis_img, (0, banner_h))
        banner_draw = ImageDraw.Draw(banner)
        status_tag = "[HIT]" if is_success else "[MISS]"
        text_str = f"{status_tag} {caption}"
        banner_draw.text((10, 8), text_str, fill=(255, 255, 255))
        return banner

    return vis_img
